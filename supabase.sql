-- =====================================================
-- Tabla: usuarios
-- =====================================================

DROP TABLE IF EXISTS usuarios CASCADE;

CREATE TABLE usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    usuario VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    edad INTEGER NOT NULL,
    ciudad VARCHAR(100) NOT NULL,
    tipo_vivienda VARCHAR(50),
    tiene_patio BOOLEAN DEFAULT FALSE,
    otras_mascotas BOOLEAN DEFAULT FALSE,
    tiempo_disponible VARCHAR(50),
    experiencia VARCHAR(255),
    preferencia_tipo VARCHAR(20),
    preferencia_tamano VARCHAR(30),
    preferencia_edad VARCHAR(30),
    rol VARCHAR(30) DEFAULT 'adoptante'
);

-- =====================================================
-- Tabla: refugios
-- =====================================================

DROP TABLE IF EXISTS refugios CASCADE;

CREATE TABLE refugios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    ciudad VARCHAR(100) NOT NULL,
    direccion VARCHAR(200),
    telefono VARCHAR(30),
    email VARCHAR(100)
);

-- =====================================================
-- Tabla: mascotas
-- =====================================================

DROP TABLE IF EXISTS mascotas CASCADE;

CREATE TABLE mascotas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refugio_id INTEGER,
    nombre VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    edad INTEGER NOT NULL,
    sexo VARCHAR(20),
    tamano VARCHAR(30),
    raza VARCHAR(100),
    ciudad VARCHAR(100),
    descripcion VARCHAR(500),
    personalidad VARCHAR(500),
    nivel_energia VARCHAR(30),
    compatible_ninos BOOLEAN DEFAULT FALSE,
    compatible_mascotas BOOLEAN DEFAULT FALSE,
    vacunado BOOLEAN DEFAULT FALSE,
    desparasitado BOOLEAN DEFAULT FALSE,
    esterilizado BOOLEAN DEFAULT FALSE,
    estado VARCHAR(30) DEFAULT 'Disponible',

    CONSTRAINT fk_mascotas_refugios
        FOREIGN KEY (refugio_id)
        REFERENCES refugios(id)
);

-- =====================================================
-- Tabla: favoritos
-- =====================================================

DROP TABLE IF EXISTS favoritos CASCADE;

CREATE TABLE favoritos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL,
    mascota_id INTEGER NOT NULL,

    CONSTRAINT uq_favoritos_usuario_mascota
        UNIQUE (usuario_id, mascota_id),

    CONSTRAINT fk_favoritos_usuarios
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id),

    CONSTRAINT fk_favoritos_mascotas
        FOREIGN KEY (mascota_id)
        REFERENCES mascotas(id)
);

-- =====================================================
-- Tabla: adopciones
-- =====================================================

DROP TABLE IF EXISTS adopciones CASCADE;

CREATE TABLE adopciones (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL,
    mascota_id INTEGER NOT NULL,
    fecha_solicitud DATE NOT NULL,
    motivo VARCHAR(500),
    lugar_mascota VARCHAR(255),
    personas_casa INTEGER,
    tiene_otras_mascotas BOOLEAN DEFAULT FALSE,
    experiencia VARCHAR(500),
    responsable VARCHAR(100),
    estado VARCHAR(30) DEFAULT 'En revisión',

    CONSTRAINT fk_adopciones_usuarios
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id),

    CONSTRAINT fk_adopciones_mascotas
        FOREIGN KEY (mascota_id)
        REFERENCES mascotas(id)
);

-- =====================================================
-- Tabla: entrevistas
-- =====================================================

DROP TABLE IF EXISTS entrevistas CASCADE;

CREATE TABLE entrevistas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adopcion_id INTEGER NOT NULL,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    modalidad VARCHAR(30),
    observaciones VARCHAR(500),
    estado VARCHAR(30) DEFAULT 'Programada',

    CONSTRAINT fk_entrevistas_adopciones
        FOREIGN KEY (adopcion_id)
        REFERENCES adopciones(id)
);

-- =====================================================
-- Tabla: historial_veterinario
-- =====================================================

DROP TABLE IF EXISTS historial_veterinario CASCADE;

CREATE TABLE historial_veterinario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mascota_id INTEGER NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    descripcion VARCHAR(500),
    fecha DATE NOT NULL,
    proxima_fecha DATE,
    veterinario VARCHAR(100),
    observaciones VARCHAR(500),

    CONSTRAINT fk_historial_mascotas
        FOREIGN KEY (mascota_id)
        REFERENCES mascotas(id)
);


